import { IAbilityEffect } from '../../ability-effect.interface';

/**
 * バトル中に効果を持たない特性の共通実装
 *
 * 用途: 野生エンカウント率・逃走可否・バトル後の道具入手のみに影響し、バトル中は何もしない特性。
 *       例:
 *       - にげあし（Run Away）: 野生バトルから必ず逃げられる（バトル中効果なし）
 *       - はっこう（Illuminate）: 野生エンカウント率を上げる（バトル中効果なし、Gen8以前）
 *       - みつあつめ（Honey Gather）: バトル後にあまいミツを拾うことがある（バトル中効果なし）
 *
 *       情報表示のみ・野生バトル専用（シングルバトルで効果なし）:
 *       - きけんよち（Anticipation）: 相手が効果抜群か一撃必殺の技を持つと知らせる（情報のみ）
 *       - よちむ（Forewarn）: 相手の一番威力の高い技を知らせる（情報のみ）
 *       - たまひろい（Ball Fetch）: 野生バトルで最初に失敗したボールを拾う（トレーナー戦では効果なし）
 *
 *       ダブルバトル専用（味方がいないシングルバトルでは効果なし）:
 *       - プラス（Plus）/ マイナス（Minus）: 味方がプラスかマイナスのとき特攻が上がる
 *       - いやしのこころ（Healer）: 味方の状態異常を治すことがある
 *       - フレンドガード（Friend Guard）: 味方が受けるダメージを減らす
 *       - テレパシー（Telepathy）: 味方の技を受けない
 *       - フラワーベール（Flower Veil）: 味方のくさタイプを能力低下と状態異常から守る
 *         （持ち主のフラベベ系統・キュワワーはくさタイプではないため、自分には働かない）
 *       - きょうせい（Symbiosis）: 道具を使った味方に自分の道具を渡す
 *       - バッテリー（Battery）: 味方の特殊技の威力を上げる
 *       - レシーバー（Receiver）/ かがくのちから（Power of Alchemy）: 倒れた味方の特性を引き継ぐ
 *       - スクリューおびれ（Propeller Tail）/ すじがねいり（Stalwart）: 技を引き寄せる効果を無視する
 *       - パワースポット（Power Spot）: 味方の技の威力を 1.3 倍にする
 *       - きみょうなくすり（Curious Medicine）: 登場時に味方の能力ランクを元に戻す
 *       - しれいとう（Commander）: 味方のヘイラッシャの口に入る
 *       - きょうえん（Costar）: 登場時に味方の能力ランクをコピーする
 *       - おもてなし（Hospitality）: 登場時に味方の HP を回復する
 *
 * 単一の stateless インスタンスを複数の特性名にエイリアス登録できる。
 * 既存の MoveRegistry の `NoOpEffect` と同様の設計。
 */
export class NoBattleEffectAbility implements IAbilityEffect {
  // すべてのオプショナルメソッドを実装しない（バトル中は何もしない）
}
